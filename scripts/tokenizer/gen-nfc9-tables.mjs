// Extract the Unicode 9.0 canonical normalization tables used by HF tokenizers' NFC
// (Rust crate unicode-normalization-alignments 0.1.12, src/tables.rs) and emit
// src/nfc9-tables.ts in a compact delta/base-36 encoding. Usage:
//   node scripts/tokenizer/gen-nfc9-tables.mjs <path/to/unicode-normalization-alignments-0.1.12/src/tables.rs>
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(process.argv[2], 'utf8');
const block = (name) => {
  const i = src.indexOf(`pub(crate) const ${name}`);
  if (i < 0) throw new Error('missing ' + name);
  return src.slice(i, src.indexOf('];', i));
};
const hex = (s) => parseInt(s, 16);
const ver = /UNICODE_VERSION: \(u64, u64, u64\) = \((\d+), (\d+), (\d+)\)/.exec(src).slice(1).join('.');

// CCC: u32 = cp << 8 | ccc
const ccc = [];
for (const m of block('CANONICAL_COMBINING_CLASS_KV').matchAll(/0x([0-9A-Fa-f]+),/g)) {
  const v = hex(m[1]);
  ccc.push([v >>> 8, v & 0xff]);
}
ccc.sort((a, b) => a[0] - b[0]);

// Canonical full decompositions: (cp, &[chars])
const dec = [];
for (const m of block('CANONICAL_DECOMPOSED_KV').matchAll(/\(0x([0-9a-fA-F]+), &\[([^\]]*)\]\)/g)) {
  dec.push([hex(m[1]), [...m[2].matchAll(/\\u\{([0-9A-Fa-f]+)\}/g)].map((x) => hex(x[1]))]);
}
dec.sort((a, b) => a[0] - b[0]);

// Composition pairs: BMP (u32 = c1 << 16 | c2) + astral match arms
const comp = [];
for (const m of block('COMPOSITION_TABLE_KV').matchAll(/\(0x([0-9A-Fa-f]+), '\\u\{([0-9A-Fa-f]+)\}'\)/g)) {
  const k = hex(m[1]);
  comp.push([k >>> 16, k & 0xffff, hex(m[2])]);
}
const astral = src.slice(src.indexOf('fn composition_table_astral'));
for (const m of astral.slice(0, astral.indexOf('_ => None')).matchAll(/\('\\u\{([0-9A-Fa-f]+)\}', '\\u\{([0-9A-Fa-f]+)\}'\) => Some\('\\u\{([0-9A-Fa-f]+)\}'\)/g))
  comp.push([hex(m[1]), hex(m[2]), hex(m[3])]);
comp.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

// Encoding: comma-separated base-36 numbers; first field of each record delta-coded.
const b36 = (n) => n.toString(36);
let prev = 0;
const cccStr = ccc.map(([c, k]) => { const d = c - prev; prev = c; return `${b36(d)},${b36(k)}`; }).join(',');
prev = 0;
const decStr = dec.map(([c, ds]) => { const d = c - prev; prev = c; return [b36(d), b36(ds.length), ...ds.map(b36)].join(','); }).join(',');
const compStr = comp.map(([a, b, c]) => [b36(a), b36(b), b36(c)].join(',')).join(',');

const ts = `// Copyright 2012-2018 The Rust Project Developers. MIT; see LICENSES/unicode-normalization-alignments-MIT.txt.\n// GENERATED by scripts/tokenizer/gen-nfc9-tables.mjs from unicode-normalization-alignments 0.1.12
// src/tables.rs (UNICODE_VERSION ${ver}): the canonical normalization data HF tokenizers' NFC uses.
// Encoding: comma-separated base-36 integers.
//   NFC9_CCC:    (deltaCp, ccc)*                      ${ccc.length} entries
//   NFC9_DECOMP: (deltaCp, n, cp1..cpn)*  full canonical decompositions, ${dec.length} entries
//   NFC9_COMP:   (first, second, composite)*          ${comp.length} primary-composite pairs
export const NFC9_UNICODE_VERSION = '${ver}';
export const NFC9_CCC = '${cccStr}';
export const NFC9_DECOMP = '${decStr}';
export const NFC9_COMP = '${compStr}';
`;
writeFileSync(new URL('../../src/tokenize/nfc9-tables.ts', import.meta.url), ts);
console.log(`unicode ${ver}: ccc=${ccc.length} decomp=${dec.length} comp=${comp.length} -> ${ts.length} bytes`);
