// Extract Oniguruma's Unicode property ranges (CR_L, CR_M, CR_N, CR_Space) from
// onig_sys-69.9.3 (Oniguruma 6.9.10, Unicode 16.0) and emit src/unicode-tables.ts.
// Usage: node scripts/tokenizer/gen-onig-tables.mjs <path/to/unicode_property_data.c>
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(process.argv[2], 'utf8');
function table(name) {
  const m = new RegExp(`\\nCR_${name}\\[\\] = \\{ (\\d+),\\n([\\s\\S]*?)\\}; /\\* END of CR_${name} \\*/`).exec(src);
  if (!m) throw new Error('missing ' + name);
  const n = +m[1];
  const nums = m[2].match(/0x[0-9a-f]+/g).map((h) => parseInt(h, 16));
  if (nums.length !== 2 * n) throw new Error(`bad count ${name}`);
  const r = [];
  for (let i = 0; i < nums.length; i += 2) r.push([nums[i], nums[i + 1]]);
  return r;
}
const ver = /#define UNICODE_PROPERTY_VERSION\s+(\d+)/.exec(src)[1];
const out = { L: table('L'), M: table('M'), N: table('N'), Space: table('Space') };
const flat = (rs) => rs.flat();
let ts = `// Copyright (c) 2016-2024 K.Kosako. BSD-2-Clause; see LICENSES/Oniguruma-Unicode-Tables.txt.\n// GENERATED by scripts/tokenizer/gen-onig-tables.mjs from onig_sys 69.9.3 (Oniguruma 6.9.10)\n` +
  `// unicode_property_data.c, UNICODE_PROPERTY_VERSION ${ver}. Do not edit.\n` +
  `// Flat [start, end, start, end, ...] inclusive code point ranges.\n`;
for (const [k, v] of Object.entries(out)) ts += `export const ONIG_${k.toUpperCase()}: readonly number[] = [${flat(v).join(',')}];\n`;
ts += `export const ONIG_UNICODE_VERSION = '${ver}';\n`;
writeFileSync(new URL('../../src/tokenize/unicode-tables.ts', import.meta.url), ts);
for (const [k, v] of Object.entries(out)) console.log(k, v.length, 'ranges');
// Compare with the running Node's ICU property escapes.
const re = { L: /\p{L}/u, M: /\p{M}/u, N: /\p{N}/u, Space: /\p{White_Space}/u };
for (const [k, rs] of Object.entries(out)) {
  const set = new Uint8Array(0x110000);
  for (const [a, b] of rs) for (let c = a; c <= b; c++) set[c] = 1;
  let onlyJs = [], onlyOnig = [];
  for (let c = 0; c < 0x110000; c++) {
    if (c >= 0xd800 && c <= 0xdfff) continue;
    const js = re[k].test(String.fromCodePoint(c)) ? 1 : 0;
    if (js && !set[c]) onlyJs.push(c); else if (!js && set[c]) onlyOnig.push(c);
  }
  const fmt = (a) => { const r = []; for (const c of a) { const l = r[r.length - 1]; if (l && l[1] === c - 1) l[1] = c; else r.push([c, c]); } return r.map(([x, y]) => x === y ? x.toString(16) : x.toString(16) + '-' + y.toString(16)).join(' '); };
  console.log(`${k}: node ${process.versions.node} (unicode ${process.versions.unicode}) only-JS=${onlyJs.length} [${fmt(onlyJs).slice(0, 400)}] only-Onig=${onlyOnig.length} [${fmt(onlyOnig).slice(0, 300)}]`);
}
