// Compute the set X of code points whose canonical-normalization data differ between
// HF tokenizers' Rust NFC (crate unicode-normalization-alignments 0.1.12) and the running
// Node's ICU. Emits src/nfc-exceptions.ts. Usage:
//   node scripts/tokenizer/gen-nfc-exceptions.mjs <path/to/unicode-normalization-alignments-0.1.12/src/tables.rs>
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(process.argv[2], 'utf8');
const block = (name) => {
  const i = src.indexOf(`pub(crate) const ${name}`);
  const j = src.indexOf('];', i);
  return src.slice(i, j);
};
const u = (s) => parseInt(s, 16);
// crate data
const ccc9 = new Map();
for (const m of block('CANONICAL_COMBINING_CLASS_KV').matchAll(/0x([0-9A-Fa-f]+),/g)) {
  const v = u(m[1]); ccc9.set(v >>> 8, v & 0xff);
}
const decomp9 = new Map();
for (const m of block('CANONICAL_DECOMPOSED_KV').matchAll(/\(0x([0-9a-fA-F]+), &\[([^\]]*)\]\)/g)) {
  decomp9.set(u(m[1]), [...m[2].matchAll(/\\u\{([0-9A-Fa-f]+)\}/g)].map((x) => u(x[1])));
}
const comp9 = new Map(); // "a,b" -> c
for (const m of block('COMPOSITION_TABLE_KV').matchAll(/\(0x([0-9A-Fa-f]+), '\\u\{([0-9A-Fa-f]+)\}'\)/g)) {
  const k = u(m[1]); comp9.set(`${k >>> 16},${k & 0xffff}`, u(m[2]));
}
const astral = src.slice(src.indexOf('fn composition_table_astral'));
for (const m of astral.slice(0, astral.indexOf('_ => None')).matchAll(/\('\\u\{([0-9A-F]+)\}', '\\u\{([0-9A-F]+)\}'\) => Some\('\\u\{([0-9A-F]+)\}'\)/g))
  comp9.set(`${u(m[1])},${u(m[2])}`, u(m[3]));
console.log('crate: ccc entries', ccc9.size, 'decomps', decomp9.size, 'comp pairs', comp9.size);
const inDecomp9 = new Set(); for (const v of decomp9.values()) for (const c of v) inDecomp9.add(c);
const known9 = (c) => ccc9.has(c) || decomp9.has(c) || inDecomp9.has(c) || (c >= 0x1100 && c <= 0x11ff) || (c >= 0xac00 && c <= 0xd7a3);
// ICU data via probes
const S = (c) => String.fromCodePoint(c);
const nonzeroCcc17 = (c) => {
  const s = S(c);
  const d = s.normalize('NFD');
  if (d !== s) return null; // has decomposition, handled separately
  return ('\u0345' + s).normalize('NFD') !== '\u0345' + s || (s + '\u0334').normalize('NFD') !== s + '\u0334';
};
const X = new Set();
const reasons = new Map();
const add = (c, why) => { if (!X.has(c)) { X.add(c); reasons.set(c, why); } };
const inDecomp17 = new Set();
for (let c = 0; c < 0x110000; c++) {
  if (c >= 0xd800 && c <= 0xdfff) continue;
  if (c >= 0xac00 && c <= 0xd7a3) continue; // Hangul: algorithmic in both
  const s = S(c);
  const d = s.normalize('NFD');
  const d9 = decomp9.get(c);
  if (d !== s) {
    const dcps = [...d].map((x) => x.codePointAt(0));
    for (const x of dcps) inDecomp17.add(x);
    if (!d9 || d9.join() !== dcps.join()) add(c, 'decomposition');
  } else {
    if (d9) add(c, 'decomposition-only-in-crate');
    const nz = nonzeroCcc17(c);
    const nz9 = (ccc9.get(c) ?? 0) !== 0;
    if (nz !== nz9) add(c, `ccc nonzero icu=${nz} crate=${nz9}`);
  }
}
for (const x of inDecomp17) if (!known9(x)) add(x, 'appears-in-icu-decomposition-only');
// Composition: for every ICU primary composite c (NFC(NFD(c)) === c, NFD length >= 2), check crate pair.
for (let c = 0; c < 0x110000; c++) {
  if (c >= 0xd800 && c <= 0xdfff) continue;
  const s = S(c);
  const d = s.normalize('NFD');
  if (d === s || s.normalize('NFC') !== s) continue;
  // canonical composition pair = decomposition (single-level) — approximate by NFC of first-but-last
  const cps = [...d].map((x) => x.codePointAt(0));
  const last = cps[cps.length - 1];
  const head = String.fromCodePoint(...cps.slice(0, -1)).normalize('NFC');
  if ([...head].length !== 1) continue;
  const k = `${head.codePointAt(0)},${last}`;
  if (comp9.get(k) !== c && !(c >= 0xac00 && c <= 0xd7a3)) {
    add(c, 'composition');
    // Only code points unknown to the crate become split points; old ones (e.g. U+0307 in
    // U+105D2 U+0307 -> U+105C9) must stay normalizable.
    for (const p of [head.codePointAt(0), last]) if (!known9(p)) add(p, 'composition-part');
  }
}
const sorted = [...X].sort((a, b) => a - b);
const ranges = []; for (const c of sorted) { const l = ranges[ranges.length - 1]; if (l && l[1] === c - 1) l[1] = c; else ranges.push([c, c]); }
console.log(`node ${process.versions.node} icu ${process.versions.icu} unicode ${process.versions.unicode}: X = ${X.size} code points in ${ranges.length} ranges`);
const byWhy = {}; for (const w of reasons.values()) byWhy[w] = (byWhy[w] || 0) + 1; console.log(byWhy);
console.log(ranges.slice(0, 80).map(([a, b]) => a === b ? a.toString(16) : `${a.toString(16)}-${b.toString(16)}`).join(' '));
