import { HELP_COMMANDS, USAGE, usageOf } from '../usage.js';
import { UsageError, type CliIO } from '../io.js';

/** One command's completions: its subcommands (or shell names) and every long flag its usage lists. */
export interface CompletionEntry {
  cmd: string;
  subs: string[];
  flags: string[];
}

const SHELLS = ['bash', 'zsh', 'fish'] as const;
type Shell = (typeof SHELLS)[number];

/** The completion table, read from USAGE so a new command or flag completes without editing this file. */
export function completionTable(): CompletionEntry[] {
  const byCmd = new Map<string, Set<string>>();
  for (const l of USAGE.split('\n\n')[1]!.split('\n')) {
    const m = /^ {2}([a-z][a-z-]*)(?: ([a-z][a-z-]*(?:\|[a-z][a-z-]*)*)(?= |$))?/.exec(l);
    if (!m) continue;
    const subs = byCmd.get(m[1]!) ?? new Set<string>();
    for (const s of m[2]?.split('|') ?? []) subs.add(s);
    byCmd.set(m[1]!, subs);
  }
  const table = [...byCmd].map(([cmd, subs]) => ({ cmd, subs: [...subs], flags: flagsOf(usageOf(cmd)) }));
  table.push({ cmd: 'help', subs: [...HELP_COMMANDS], flags: [] });
  return table;
}

function flagsOf(text: string): string[] {
  const flags = new Set([...text.matchAll(/(?<![\w-])--([a-z][a-z-]*)/g)].map((m) => `--${m[1]}`));
  flags.add('--help');
  return [...flags];
}

export function completionScript(shell: Shell, table: CompletionEntry[] = completionTable()): string {
  const cmds = table.map((e) => e.cmd).join(' ');
  if (shell === 'bash') {
    const cases = table.map((e) => `    ${e.cmd}) subs='${e.subs.join(' ')}'; flags='${e.flags.join(' ')}' ;;`);
    return `# kitzur bash completion, generated by \`kitzur completions bash\`
# load it with: source <(kitzur completions bash)
_kitzur() {
  local cur=\${COMP_WORDS[COMP_CWORD]} subs='' flags=''
  COMPREPLY=()
  if [ "$COMP_CWORD" -eq 1 ]; then
    COMPREPLY=($(compgen -W '${cmds}' -- "$cur"))
    return 0
  fi
  case \${COMP_WORDS[1]} in
${cases.join('\n')}
  esac
  if [[ $cur == -* ]]; then
    COMPREPLY=($(compgen -W "$flags" -- "$cur"))
  elif [ "$COMP_CWORD" -eq 2 ] && [ -n "$subs" ]; then
    COMPREPLY=($(compgen -W "$subs" -- "$cur"))
  fi
  return 0
}
complete -o default -F _kitzur kitzur
`;
  }
  if (shell === 'zsh') {
    const cases = table.map((e) => `    ${e.cmd}) subs=(${e.subs.join(' ')}); flags=(${e.flags.join(' ')}) ;;`);
    return `#compdef kitzur
# kitzur zsh completion, generated by \`kitzur completions zsh\`
# load it with: source <(kitzur completions zsh), or save it as _kitzur in your $fpath
_kitzur() {
  local -a subs flags
  if (( CURRENT == 2 )); then
    compadd -- ${cmds}
    return
  fi
  case $words[2] in
${cases.join('\n')}
  esac
  if [[ $PREFIX == -* ]]; then
    compadd -a flags
  elif (( CURRENT == 3 && $#subs )); then
    compadd -a subs
  else
    _files
  fi
}
if [ "$funcstack[1]" = _kitzur ]; then _kitzur "$@"; else compdef _kitzur kitzur; fi
`;
  }
  const lines = [
    '# kitzur fish completion, generated by `kitzur completions fish`',
    '# load it with: kitzur completions fish | source',
    'function __kitzur_at; set -l w (commandline -opc); test (count $w) -eq 2; and test $w[2] = $argv[1]; end',
    'function __kitzur_in; set -l w (commandline -opc); test (count $w) -ge 2; and test $w[2] = $argv[1]; end',
    `complete -c kitzur -n __fish_use_subcommand -f -a '${cmds}'`,
  ];
  for (const e of table) {
    if (e.subs.length) lines.push(`complete -c kitzur -n '__kitzur_at ${e.cmd}' -f -a '${e.subs.join(' ')}'`);
    for (const f of e.flags) lines.push(`complete -c kitzur -n '__kitzur_in ${e.cmd}' -l ${f.slice(2)}`);
  }
  return lines.join('\n') + '\n';
}

export function cmdCompletions(argv: string[], io: CliIO): number {
  const [shell, ...rest] = argv;
  if (!SHELLS.includes(shell as Shell)) {
    throw new UsageError(shell ? `unknown shell '${shell}' (bash, zsh, fish)` : 'completions needs a shell: bash, zsh, fish');
  }
  if (rest.length) throw new UsageError(`completions ${shell} takes no arguments (got ${rest.join(' ')})`);
  io.stdout(completionScript(shell as Shell));
  return 0;
}
